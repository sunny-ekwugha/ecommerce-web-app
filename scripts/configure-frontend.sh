#!/usr/bin/env bash
# Writes frontend/react-app/src/aws-config.js from the Terraform outputs.
# Never edit that file by hand and never commit it: the values belong to one deployment.
# Run this after `terraform apply` of the cognito and api modules, before `npm run build`.
set -euo pipefail

ROOT="$(git rev-parse --show-toplevel)"
OUT="${ROOT}/frontend/react-app/src/aws-config.js"
cd "${ROOT}/terraform/envs/prod"

# Read one output; stop with a clear message if it is missing (for example, the API is not applied yet).
get() {
  local v
  v="$(terraform output -raw "$1" 2>/dev/null | tr -d '\r' || true)"
  if [ -z "${v}" ]; then
    echo "ERROR: terraform output '$1' is empty or missing. Apply the module that provides it first." >&2
    exit 1
  fi
  printf '%s' "${v}"
}

POOL_ID="$(get cognito_user_pool_id)"
CLIENT_ID="$(get cognito_client_id)"
API_URL="$(get api_endpoint)"

case "${API_URL}" in
  https://*) ;;
  *) echo "ERROR: api_endpoint does not start with https:// (got '${API_URL}')." >&2; exit 1 ;;
esac
API_URL="${API_URL%/}"   # the app appends paths that start with /

cat > "${OUT}.tmp" <<EOF
// GENERATED by scripts/configure-frontend.sh from terraform output. Do not edit. Do not commit.
const awsConfig = {
  Auth: {
    Cognito: {
      userPoolId: '${POOL_ID}',
      userPoolClientId: '${CLIENT_ID}',
      loginWith: {
        email: true,
      },
    }
  },
  API: {
    baseUrl: '${API_URL}'
  }
};

export default awsConfig;
EOF
mv "${OUT}.tmp" "${OUT}"

echo "Wrote ${OUT}"
echo "API base URL: ${API_URL}"